    public void tampilkanData() {
        tabel1.setRowCount(0);
        
        if (con == null) {
            JOptionPane.showMessageDialog(null, "Database belum terkoneksi! Pastikan XAMPP nyala dan database 'pbo' sudah dibuat.", "Error Koneksi", JOptionPane.ERROR_MESSAGE);
            return; // Hentikan proses agar form tidak crash
        }
        try {
            java.sql.Statement st = con.createStatement();
            java.sql.ResultSet rs = st.executeQuery("SELECT * FROM mhs");
            int no = 1;
            while(rs.next()){
                Object[] row = new Object[9];
                row[0] = no++;
                row[1] = rs.getString("nim");
                row[2] = rs.getString("nama");
                row[3] = rs.getDouble("nilai_uts");
                row[4] = rs.getDouble("nilai_uas");
                row[5] = rs.getDouble("nilai_tugas");
                row[6] = rs.getDouble("nilai_akhir");
                row[7] = rs.getString("nilai_huruf");
                row[8] = rs.getString("predikat");
                tabel1.addRow(row);
            }
        } catch (java.sql.SQLException ex) {
            JOptionPane.showMessageDialog(null, "Gagal memuat tabel: " + ex.getMessage());
        }
    }

