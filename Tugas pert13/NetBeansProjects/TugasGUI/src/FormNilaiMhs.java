    private void prosesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_prosesActionPerformed
                                                                          
    try {
            double uts = Double.parseDouble(nUTS.getText());
            double uas = Double.parseDouble(nUAS.getText());
            double tgs = Double.parseDouble(nTugas.getText());

            Mhs m = new Mhs(nim.getText(), nama.getText(), uts, uas, tgs);

            nUTS1.setText(String.format(java.util.Locale.US, "%.2f", m.getUtsPersen()));
            nUAS1.setText(String.format(java.util.Locale.US, "%.2f", m.getUasPersen()));
            nTugas1.setText(String.format(java.util.Locale.US, "%.2f", m.getTugasPersen()));
            nUTS2.setText(String.format(java.util.Locale.US, "%.2f", m.getNilaiAkhir()));
            
            nUAS2.setText(m.getPredikat()); 
            nTugas2.setText(m.getNilaiHuruf());
            
            simpan.setEnabled(true);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Input harus angka!");
        }    // TODO add your handling code here:
    }//GEN-LAST:event_prosesActionPerformed

    private void simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanActionPerformed
try {
            String sql = "INSERT INTO mhs (nim, nama, nilai_uts, nilai_uas, nilai_tugas, nilai_akhir, nilai_huruf, predikat) VALUES (?,?,?,?,?,?,?,?)";
            java.sql.PreparedStatement ps = con.prepareStatement(sql);
            
            ps.setString(1, nim.getText());
            ps.setString(2, nama.getText());
            ps.setDouble(3, Double.parseDouble(nUTS.getText()));
            ps.setDouble(4, Double.parseDouble(nUAS.getText()));
            ps.setDouble(5, Double.parseDouble(nTugas.getText()));
            
            // Antisipasi jika String.format memunculkan koma (,), ganti jadi titik (.) agar DB menerima
            ps.setDouble(6, Double.parseDouble(nUTS2.getText().replace(",", "."))); 
            ps.setString(7, nTugas2.getText());
            ps.setString(8, nUAS2.getText());
            
            ps.executeUpdate();
            JOptionPane.showMessageDialog(null, "Data berhasil tersimpan!");
            tampilkanData();
            kosongkanTextField();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(null, "Gagal simpan: " + ex.getMessage());
            ex.printStackTrace();
        } // TODO add your handling code here:
    }//GEN-LAST:event_simpanActionPerformed

